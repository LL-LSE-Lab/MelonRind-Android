"""Generate the embedded overlay art used by the AppleSkin-style HUD overlay.

The two shapes come from the sibling desktop mod (`MelonRind`), which ships them
as 9x9 RGBA sprites matching one vanilla HUD icon:

    resource_packs/melonrind/textures/melonrind/saturation.png   gold drumstick outline
    resource_packs/melonrind/textures/melonrind/regen.png        green heart

They are embedded here so the Android build has no runtime asset dependency (the
launcher's preloader HUD API can only draw images that were registered from
memory).  The food-preview shape is the same drumstick outline recoloured to a
pale warm white, because the launcher HUD API cannot tint an image: every colour
has to be baked into the registered pixels.

Usage:

    python tools/generate_overlay_art.py ^
        --source "E:/dev/BDS/dev/project/MelonRind/resource_packs/melonrind/textures/melonrind" ^
        --output src/runtime/generated/OverlayArt.h
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

ART_SIZE = 9
PREVIEW_COLOUR = (255, 248, 225)


def load_rgba(path: Path) -> Image.Image:
    image = Image.open(path)
    if image.mode != "RGBA":
        image = image.convert("RGBA")
    if image.size != (ART_SIZE, ART_SIZE):
        raise SystemExit(f"{path}: expected a {ART_SIZE}x{ART_SIZE} sprite, got {image.size}")
    return image


def recolour(image: Image.Image, colour: tuple[int, int, int]) -> Image.Image:
    result = Image.new("RGBA", image.size)
    source = image.load()
    target = result.load()
    for y in range(image.size[1]):
        for x in range(image.size[0]):
            alpha = source[x, y][3]
            target[x, y] = (colour[0], colour[1], colour[2], alpha)
    return result


def format_bytes(image: Image.Image, name: str) -> str:
    values = list(image.tobytes())
    lines: list[str] = []
    for start in range(0, len(values), 12):
        chunk = ", ".join(f"0x{value:02x}" for value in values[start:start + 12])
        lines.append(f"    {chunk},")
    body = "\n".join(lines)
    return (f"inline constexpr unsigned char {name}[kOverlayArtBytes] = {{\n{body}\n}};\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    saturation = load_rgba(args.source / "saturation.png")
    regen = load_rgba(args.source / "regen.png")
    preview = recolour(saturation, PREVIEW_COLOUR)

    header = [
        "// Generated by tools/generate_overlay_art.py; do not edit by hand.",
        "//",
        "// One 9x9 RGBA sprite per overlay treatment, matching a single vanilla HUD",
        "// icon (9 units square, 8 units of pitch).  The saturation and regen shapes",
        "// come from the sibling desktop mod; the food preview reuses the saturation",
        "// shape in a pale colour because the launcher HUD API cannot tint images.",
        "#pragma once",
        "",
        "namespace melonrind::generated {",
        "",
        "constexpr int kOverlayArtUnits = 9;",
        f"constexpr int kOverlayArtBytes = {ART_SIZE * ART_SIZE * 4};",
        "",
        format_bytes(saturation, "kSaturationArt"),
        format_bytes(preview, "kFoodPreviewArt"),
        format_bytes(regen, "kRegenArt"),
        "} // namespace melonrind::generated",
        "",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(header), encoding="ascii", newline="\n")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
